import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const GENERATED_PATH = path.join(
  packageRoot,
  "src",
  "generated",
  "schema-validators.ts"
);

const SCHEMAS = [
  ["validateCommandRequestV1", "command-request.v1.schema.json"],
  ["validateCommandResponseV1", "command-response.v1.schema.json"],
  ["validateHostCapabilitiesV1", "host-capabilities.v1.schema.json"],
  ["validatePresetDefinitionV1", "preset-definition.v1.schema.json"],
  ["validatePresetDefinitionV2", "preset-definition.v2.schema.json"],
  ["validateRigMetadataV1", "rig-metadata.v1.schema.json"]
];

/**
 * O `esm: true` do AJV governa apenas os `export`; os helpers de runtime
 * (`equal`, `ucs2length`) continuam entrando como
 * `require("ajv/dist/runtime/X")` porque essa string vem gravada no proprio
 * modulo do AJV, e nao no gerador de codigo. Num pacote `"type": "module"` isso
 * e um ReferenceError no primeiro import, e trocar por `import` mudaria so o
 * sintoma: o artefato standalone existe justamente para nao depender do AJV em
 * runtime — o AJV e devDependency e nao estara presente numa instalacao de
 * producao.
 *
 * Entao inlinamos. A fonte sai do `Function.prototype.toString()` do modulo
 * instalado, nunca de uma copia manual, para o artefato nao divergir da versao
 * do AJV que gerou os validadores. Os dois helpers sao declaracoes de funcao
 * fechadas (a recursao do `equal` usa o proprio nome), entao o texto vale
 * sozinho; a IIFE isola esse nome dos identificadores que o AJV emite.
 */
const REQUIRE_DE_RUNTIME = /^const (\w+) = require\("ajv\/dist\/runtime\/([\w-]+)"\)\.default;$/gm;

async function inlineRuntimeHelpers(codigo) {
  const substituicoes = [];
  for (const [linha, nomeLocal, modulo] of codigo.matchAll(REQUIRE_DE_RUNTIME)) {
    const importado = await import(`ajv/dist/runtime/${modulo}.js`);
    const helper = importado.default && importado.default.default;
    const fonte = typeof helper === "function" ? helper.toString() : null;
    if (fonte === null || !/^function\s/.test(fonte)) {
      throw new Error(
        `ajv/dist/runtime/${modulo} nao exporta uma declaracao de funcao inlinavel.`
      );
    }
    const nomeDaFuncao = fonte.slice("function ".length, fonte.indexOf("(")).trim();
    substituicoes.push([
      linha,
      [
        `// Inlinado de ajv/dist/runtime/${modulo} por gen-schema-validators.mjs.`,
        `const ${nomeLocal} = (function () {`,
        fonte,
        `return ${nomeDaFuncao};`,
        "})();"
      ].join("\n")
    ]);
  }

  let saida = codigo;
  for (const [linha, bloco] of substituicoes) saida = saida.replace(linha, bloco);

  if (/\brequire\(/.test(saida)) {
    throw new Error(
      "Ainda ha require() no codigo standalone do AJV; o modulo quebraria ao ser importado como ESM."
    );
  }
  return saida;
}

export async function renderModule() {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    // `reasonKey` e os campos exclusivos de host são condicionais; eles estão
    // declarados no objeto pai e exigidos apenas em subschemas `then`.
    strictRequired: false,
    strictNumbers: true,
    unicodeRegExp: false,
    code: { source: true, esm: true, lines: true }
  });
  const exportsByName = {};

  for (const [exportName, filename] of SCHEMAS) {
    const source = await readFile(path.join(packageRoot, "schemas", filename), "utf8");
    const schema = JSON.parse(source);
    // `$schema`, `$id` e `title` versionam/documentam o artefato fonte, mas não
    // participam da validação. Removê-los da cópia de runtime impede que URLs
    // documentais vazem para os bundles fechados por allowlist dos painéis.
    const runtimeSchema = Object.fromEntries(
      Object.entries(schema).filter(([key]) => !["$schema", "$id", "title"].includes(key))
    );
    const schemaKey = `motion.contract.${filename}`;
    ajv.addSchema(runtimeSchema, schemaKey);
    exportsByName[exportName] = schemaKey;
  }

  const generated = await inlineRuntimeHelpers(standaloneCode(ajv, exportsByName));
  return [
    "// @ts-nocheck",
    "// GENERATED by packages/contracts/scripts/gen-schema-validators.mjs.",
    "// Do not edit by hand; generated-drift.test.mjs is authoritative.",
    generated.trimEnd(),
    ""
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await mkdir(path.dirname(GENERATED_PATH), { recursive: true });
  await writeFile(GENERATED_PATH, await renderModule(), "utf8");
  console.log(`Validadores standalone gerados em ${path.relative(packageRoot, GENERATED_PATH)}.`);
}
