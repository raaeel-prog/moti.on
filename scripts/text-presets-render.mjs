/** Cards sit on black. The fixture keeps its grey so earlier renders and the
 * comparison stay valid; a linear level maps it to black, which equals the
 * white type composited over black, antialiasing included. */
function blackLevels(fixture) {
  const floor = Math.round(fixture.background[0] * 255) + 2, level = `clip((val-${floor})*255/${255 - floor},0,255)`;
  return `lutrgb=r='${level}':g='${level}':b='${level}'`;
}
/** Shipped size of every preview: the largest a card ever draws (previewSpec
 * caps decoding at 320 px), so the panel never decodes pixels it throws away.
 * AE still renders at the fixture's 480 × 270; only the shipped copy shrinks. */
export const PREVIEW_SHIP_SIZE = Object.freeze({ width: 320, height: 180 });
const shipScale = `scale=${PREVIEW_SHIP_SIZE.width}:${PREVIEW_SHIP_SIZE.height}:flags=lanczos`;
/** Many cards decode at once: no B-frames or CABAC, and a keyframe each second
 * so a card joining the shared preview clock seeks quickly. Flat white type on
 * a flat ground holds up at CRF 27, about half the bytes of CRF 23. */
const CARD_VIDEO_ENCODE = ["-c:v", "libx264", "-preset", "veryslow", "-crf", "27", "-tune", "fastdecode", "-bf", "0", "-g", "30", "-pix_fmt", "yuv420p", "-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709", "-color_range", "tv", "-movflags", "+faststart"];
const POSTER_QUALITY = ["-q:v", "5"];
/** ffmpeg arguments for one shipped card video from the lossless AE render. */
const cardVideoArgs = (avi, fixture, output) => ["-hide_banner", "-loglevel", "error", "-y", "-i", avi, "-an", "-vf", `format=gbrp,${blackLevels(fixture)},${shipScale},scale=out_color_matrix=bt709:out_range=tv,format=yuv420p`, ...CARD_VIDEO_ENCODE, output];
/** ffmpeg arguments for one shipped poster at `time` seconds of the render. */
const posterArgs = (avi, fixture, time, output) => ["-hide_banner", "-loglevel", "error", "-y", "-ss", String(time), "-i", avi, "-frames:v", "1", "-vf", `format=rgb24,${blackLevels(fixture)},${shipScale}`, ...POSTER_QUALITY, output];

/** How much text each frame shows (grey levels above the fixture background),
 * sampled at `rate` per second in one decode of the lossless render. */
function inkSeries(avi, fixture, rate = 10) {
  const width = 96, height = 54;
  const frames = spawnSync(ffmpeg, ["-hide_banner", "-loglevel", "error", "-i", avi, "-vf", `fps=${rate},scale=${width}:${height}`, "-f", "rawvideo", "-pix_fmt", "gray", "-"], {maxBuffer: 1 << 26});
  if (frames.status !== 0 || !frames.stdout.length) return [];
  const background = fixture.background[0] * 255 + 6, size = width * height, series = [];
  for (let at = 0; at + size <= frames.stdout.length; at += size) {
    let sum = 0; for (let i = at; i < at + size; i++) sum += Math.max(0, frames.stdout[i] - background);
    series.push(sum);
  }
  return series;
}
/** The resting still: the middle of the longest stretch where the text shows
 * in full, so a card at rest reads every letter in white. A still caught
 * mid-entrance looked grey and cut ("OTIO") once a preview ended on it. */
export function restingPosterTime(series, rate = 10) {
  // A one-frame flash (glitch, flicker) is not the resting text.
  const steady = series.map((value, i) => [series[i - 1] ?? value, value, series[i + 1] ?? value].sort((a, b) => a - b)[1]);
  const level = Math.max(0, ...steady);
  if (level <= 0) return 1.8;
  let best = [0, 0], start = -1;
  for (let i = 0; i <= series.length; i++) {
    const full = i < series.length && steady[i] >= level * .95;
    if (full && start < 0) start = i;
    if (!full && start >= 0) { if (i - start > best[1] - best[0]) best = [start, i]; start = -1; }
  }
  return Number(((best[0] + best[1] - 1) / 2 / rate).toFixed(2));
}
function posterTime(avi, fixture) { return restingPosterTime(inkSeries(avi, fixture)); }

