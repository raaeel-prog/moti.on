async function run(executable, parameters, logName, timeoutMs = 600000, finished) {
  console.log(`START ${path.basename(executable)} ${parameters.slice(0, 3).join(" ")}`);
  const child = spawn(executable, parameters, { cwd: root, windowsHide: true, stdio: executable === fixtureAE ? "ignore" : ["ignore", "pipe", "pipe"] });
  console.log(`PID ${child.pid}`);
  let output = "";
  child.stdout?.on("data", value => { output += value; if (executable === aerender) process.stdout.write(value); });
  child.stderr?.on("data", value => { output += value; });
  let expired = false, lingering = false, doneSince = 0;
  const timer = setTimeout(() => { expired = true; child.kill(); }, timeoutMs);
  // The isolated AE sometimes stays open after app.quit(): once its work is
  // reported as finished, give it a minute to exit, then close that instance.
  const watcher = finished ? setInterval(async () => {
    if (!await finished()) { doneSince = 0; return; }
    doneSince ||= Date.now();
    if (Date.now() - doneSince > 60000) { lingering = true; child.kill(); }
  }, 5000) : undefined;
  const code = await new Promise((resolve, reject) => { child.once("error", reject); child.once("close", resolve); });
  clearTimeout(timer); if (watcher) clearInterval(watcher);
  await writeFile(path.join(evidence, logName), output, "utf8");
  if (lingering) { console.log(`Isolated process ${child.pid} finished its work but did not exit; closed it`); return; }
  if (expired) throw new Error(`Isolated process ${child.pid} exceeded its deadline; see ${logName}`);
  if (code !== 0) throw new Error(`${path.basename(executable)} exited ${code}; see ${logName}`);
}

