async function run(executable, parameters, logName, timeoutMs = 600000) {
  console.log(`START ${path.basename(executable)} ${parameters.slice(0, 3).join(" ")}`);
  const child = spawn(executable, parameters, { cwd: root, windowsHide: true, stdio: executable === fixtureAE ? "ignore" : ["ignore", "pipe", "pipe"] });
  console.log(`PID ${child.pid}`);
  let output = "";
  child.stdout?.on("data", value => { output += value; if (executable === aerender) process.stdout.write(value); });
  child.stderr?.on("data", value => { output += value; });
  let expired = false;
  const timer = setTimeout(() => { expired = true; child.kill(); }, timeoutMs);
  const code = await new Promise((resolve, reject) => { child.once("error", reject); child.once("close", resolve); });
  clearTimeout(timer);
  await writeFile(path.join(evidence, logName), output, "utf8");
  if (expired) throw new Error(`Isolated process ${child.pid} exceeded its deadline; see ${logName}`);
  if (code !== 0) throw new Error(`${path.basename(executable)} exited ${code}; see ${logName}`);
}

async function prepare() {
  const host = path.join(root, "dist", "after-effects-cep", "host", "index.jsx");
  if (!await exists(host)) throw new Error("Build the candidate host first: npm.cmd run build");
  const compilation = await build({ entryPoints: [path.join(root, "packages", "contracts", "src", "motion-library.ts")], bundle: true, format: "esm", platform: "node", write: false });
  const catalog = await import(`data:text/javascript;base64,${Buffer.from(compilation.outputFiles[0].text).toString("base64")}`);
  const capability = await readJson(path.join(evidence, "ae-capabilities.json"));
  if (capability.status !== "PASS") throw new Error("AE capability probe must PASS before fixture creation");
  const hostSha256 = hash(await readFile(host));
  const executionHost = normalized(path.join(evidence, "fixture-host.jsx"));
  const executionSource = (await readFile(host, "utf8")).replace(/^#target aftereffects\r?\n/, "");
  await writeFile(executionHost, executionSource);
  const textEngineSha256=await textEngineDigest();
  let oldManifest = {schemaVersion: 1, presets: {}};
  if (await exists(path.join(assets, "manifest.json"))) oldManifest = await readJson(path.join(assets, "manifest.json"));
  const limitArg = process.argv.find(value => value.startsWith("--limit="));
  const limit = limitArg ? Number(limitArg.slice(8)) : Infinity;
  const recipes = catalog.MOTION_LIBRARY_PRESETS.filter(preset => preset.collection === "text").slice(0, limit);
  if (!recipes.length) throw new Error("No original text collection recipes found");
  const entries = recipes.map(preset => {
    const options = {durationFrames: 24, intensity: 100, staggerFrames: 2, phase: "both", direction: "preset", unit: "preset", easing: "preset", order: "preset", seed: 17, elasticity: 30, overlap: 65, speed: 100, ...preset.defaults};
    options.phase = "both";
    const recipeHash = hash(JSON.stringify({preset, options, fixture: TEXT_PREVIEW_FIXTURE, textEngineSha256, hostVersion: capability.version}));
    return {id: preset.id, mode: preset.mode, recipeHash, options, recipe: preset, avi: normalized(path.join(evidence, "raw", `${preset.id}.avi`)), cached: oldManifest.presets[preset.id]?.hash === recipeHash};
  });
  for (const entry of entries) entry.cached = entry.cached && await exists(path.join(assets, `${entry.id}.mp4`)) && await exists(path.join(assets, `${entry.id}.jpg`));
  const job = {schemaVersion: 1, fixture: TEXT_PREVIEW_FIXTURE, host: executionHost, sourceHost: normalized(host), executionHostSha256: hash(executionSource), expectedCatalogCount: catalog.MOTION_LIBRARY_PRESETS.length, hostVersion: capability.version, hostSha256,textEngineSha256, aep: normalized(path.join(evidence, "text-previews.aep")), report: normalized(path.join(evidence, "fixture-report.json")), entries};
  await saveJson(path.join(evidence, "render-job.json"), job);
  const source = `/* Generated from original Moti.on recipes; guarded isolated project only. */\n(function(){\nvar job=${JSON.stringify(job)};\n${await readFile(new URL("./text-presets-fixture.jsx", import.meta.url), "utf8")}\n}());\n`;
  await writeFile(path.join(evidence, "build-fixtures.jsx"), toAsciiExtendScript(groupConditionalBranches(source), "build-fixtures.jsx"), "utf8");
  // The GUI executable owns a separate process with -m and exits after the
  // guarded fixture. The console host can remain alive after app.quit().
  await run(fixtureAE, ["-m", "-r", path.join(evidence, "build-fixtures.jsx")], "fixture-launch.log");
  const report = await readJson(job.report);
  if (report.status !== "PASS") throw new Error(`Fixture creation ${report.status}; inspect ${job.report}`);
  console.log(`FIXTURE PASS ${report.entries.length} original recipes; ${entries.filter(entry => entry.cached).length} cached`);
  return job;
}

async function render() {
  const job = await readJson(path.join(evidence, "render-job.json"));
  const report = await readJson(job.report);
  if (report.status !== "PASS") throw new Error("Refusing to render failed fixtures");
  const pending = job.entries.filter(entry => !entry.cached);
  if (pending.length) await run(aerender, ["-project", job.aep, "-v", "ERRORS_AND_PROGRESS", "-log", path.join(evidence, "aerender.log")], "aerender-stdout.log", 3600000);
  let manifest = {schemaVersion: 1, presets: {}};
  if (await exists(path.join(assets, "manifest.json"))) manifest = await readJson(path.join(assets, "manifest.json"));
  manifest.fixture = job.fixture; manifest.hostVersion = job.hostVersion; manifest.hostSha256 = job.hostSha256; manifest.textEngineSha256 = job.textEngineSha256;
  for (const entry of job.entries) {
    if (!entry.cached) {
      await run(ffmpeg, ["-hide_banner", "-loglevel", "error", "-y", "-i", entry.avi, "-an", "-c:v", "libx264", "-preset", "fast", "-crf", "20", "-pix_fmt", "yuv420p", "-movflags", "+faststart", path.join(assets, `${entry.id}.mp4`)], `${entry.id}-encode.log`);
      await run(ffmpeg, ["-hide_banner", "-loglevel", "error", "-y", "-ss", "1.8", "-i", entry.avi, "-frames:v", "1", "-q:v", "3", path.join(assets, `${entry.id}.jpg`)], `${entry.id}-poster.log`);
    }
    manifest.presets[entry.id] = {video: `${entry.id}.mp4`, poster: `${entry.id}.jpg`, hash: entry.recipeHash, durationSeconds: job.fixture.durationSeconds, text: job.fixture.text, options: entry.options, fixtureVersion: job.fixture.version, hostVersion: job.hostVersion};
    await saveJson(path.join(assets, "manifest.json"), manifest);
    console.log(`ASSET PASS ${entry.id}${entry.cached ? " cached" : " rendered"}`);
  }
  await saveJson(path.join(evidence, "render-summary.json"), {status: "PASS", hostVersion: job.hostVersion, hostSha256: job.hostSha256, fixture: job.fixture, count: job.entries.length, rendered: pending.length, cached: job.entries.length - pending.length, completedAt: new Date().toISOString()});
  await generateManifestModule(manifest);
}

