export async function textEngineDigest(){
  // Layer-only Momentum geometry cannot change a native Text Animator render.
  const library=await readFile(path.join(root,"apps/after-effects-cep/host/src/commands/preset-library.jsx"),"utf8");
  const start=library.indexOf("  function layerAnimation(plan)"),end=library.indexOf("  /** Measured travel",start);
  if(start<0||end<0)throw Error("Text renderer boundaries changed; review the cache key");
  // This exact rejection only protects a foreign metadata layout, which cannot
  // occur in an authored preview. Any other edit still invalidates the cache.
  const foreignSlotGuard='    // A parallel rig format uses slots.effect; never edit it as textEffect.\n    if(r.slots.effect)throw new Error("Este rig usa outro formato de efeito. Recarregue a atualizacao que o criou antes de editar.");\n';
  let phaseSource=(await readFile(path.join(root,"apps/after-effects-cep/host/src/commands/preset-phases.jsx"),"utf8")).replace(foreignSlotGuard,'');
  // Fresh preview layers cannot enter restoration of a previous rig. Keep the
  // successful render projection stable when that recovery path is repaired.
  for(const marker of ['ROLLBACK_ONLY','ROLLBACK_STATE']){
    const begin=phaseSource.indexOf(marker==='ROLLBACK_ONLY'?'  // '+marker+'_BEGIN\n':'      // '+marker+'_BEGIN\n');
    const endToken=(marker==='ROLLBACK_ONLY'?'  // ':'      // ')+marker+'_END\n',end=phaseSource.indexOf(endToken);
    if(begin>=0){if(end<begin)throw Error('Incomplete rollback-only cache boundary');phaseSource=phaseSource.slice(0,begin)+phaseSource.slice(end+endToken.length);}
  }
  phaseSource=phaseSource.replaceAll('restoreExact(d.q.layer,d.oldRoot,d.q.rollbackExact);','').replaceAll('restoreExact(d.q.layer,{textEffect:{meta:m},slots:{},shared:[]},d.q.rollbackExact);','');
  return hash(library.slice(0,start)+library.slice(end)+await readFile(path.join(root,"packages/contracts/src/motion-library-math.ts"),"utf8")+phaseSource);
}
